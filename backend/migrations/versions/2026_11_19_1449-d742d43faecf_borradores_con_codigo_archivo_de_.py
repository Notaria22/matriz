def _texto_busqueda(contenido):
    valores = []

    def recorrer(x):
        if isinstance(x, dict):
            for k, v in x.items():
                if k in CLAVES_BUSQUEDA and isinstance(v, (str, int)) and str(v).strip():
                    valores.append(str(v).strip())
                else:
                    recorrer(v)
        elif isinstance(x, list):
            for v in x:
                recorrer(v)

    recorrer(contenido)
    return " ".join(dict.fromkeys(valores))[:5000]


def _cargar(valor):
    if isinstance(valor, (dict, list)):
        return valor
    try:
        return json.loads(valor) if valor else None
    except (TypeError, ValueError):
        return None


def _numerar(conn, tabla, columna_fecha, columna_json, tipo):
    """Da códigos AAAA-MM-000001 a las filas existentes, en orden de creación, y deja el contador al día."""
    filas = conn.execute(sa.text(
        f"SELECT id, {columna_fecha}, {columna_json} FROM {tabla} ORDER BY {columna_fecha}, id"
    )).fetchall()
    ultimos = {}
    for id_, fecha, contenido in filas:
        fecha = fecha or datetime.now()
        clave = (fecha.year, fecha.month)
        ultimos[clave] = ultimos.get(clave, 0) + 1
        conn.execute(
            sa.text(f"UPDATE {tabla} SET codigo = :codigo, texto_busqueda = :texto WHERE id = :id"),
            {
                "codigo": f"{fecha.year}-{fecha.month:02d}-{ultimos[clave]:06d}",
                "texto": _texto_busqueda(_cargar(contenido)),
                "id": id_,
            },
        )
    for (anio, mes), ultimo in ultimos.items():
        conn.execute(
            sa.text("INSERT INTO contadores_mensuales (tipo, anio, mes, ultimo) VALUES (:t, :a, :m, :u)"),
            {"t": tipo, "a": anio, "m": mes, "u": ultimo},
        )


